_VENUE_SHORT = {}
_FULL_TO_SHORT = {}
for _area in VENUES.values():
    for _short, _info in _area["conferences"].items():
        if _info["s2"]:
            _VENUE_SHORT[_info["s2"]] = _short
        _FULL_TO_SHORT[_info["full"]] = _short


def short_venue(venue: str | None) -> str:
    if not venue:
        return ""
    if venue in _VENUE_SHORT:
        return _VENUE_SHORT[venue]
    if venue in _FULL_TO_SHORT:
        return _FULL_TO_SHORT[venue]
    return venue[:15]


def all_s2_venues() -> list[str]:
    return [_info["s2"] for _area in VENUES.values() for _info in _area["conferences"].values() if _info["s2"]]


def s2_venues_by_area(area: str) -> list[str]:
    if area not in VENUES:
        return []
    return [_info["s2"] for _info in VENUES[area]["conferences"].values() if _info["s2"]]


def unsupported_venues() -> list[str]:
    return [_short for _area in VENUES.values() for _short, _info in _area["conferences"].items() if not _info["s2"]]
